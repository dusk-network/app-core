#!/usr/bin/env node
/**
 * Unicode's confusables (UTS #39, confusables.txt) as src/confusables.js has
 * them for /names: each character that looks like another, and the characters
 * it looks like. The file is the pinned version's, checked against its hash
 * before anything is written: fetched from unicode.org, or read from a copy.
 *
 *   node scripts/generate-confusables.js [path/to/confusables.txt]
 *
 * For a new Unicode version, change SOURCE to its URL and the file's hash.
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const SOURCE = Object.freeze({
  version: "18.0.0",
  url: "https://www.unicode.org/Public/18.0.0/security/confusables.txt",
  sha256: "6ed3ee967c9dfdf6677d563c9985182fbc50a2efb7d6059cd57b2e2ce18f5b92",
});

/** Entries a line of the module holds. */
const PER_LINE = 24;

/**
 * The file's mappings, by their source's code point: each a code point and
 * the code points it looks like.
 *
 * @param {string} text
 * @returns {[number, number[]][]}
 */
export function parseConfusables(text) {
  /** @type {Map<number, number[]>} */
  const map = new Map();

  for (const line of text.split("\n")) {
    const body = line.split("#")[0].trim();

    if (!body) continue;

    const [source, target, type] = body.split(";").map((field) => field.trim());
    const hex = /^[0-9A-F]{4,6}$/;
    const targets = target.split(/\s+/);

    if (type !== "MA" || !hex.test(source) || !targets.every((each) => hex.test(each))) throw new Error(`Not a confusables line: ${line}`);

    map.set(Number.parseInt(source, 16), targets.map((each) => Number.parseInt(each, 16)));
  }

  return [...map].sort(([a], [b]) => a - b);
}

/**
 * The module's text, from the file's: its header, which carries Unicode's
 * notice, and the table, a line of entries at a time.
 *
 * @param {string} text
 * @param {{ version: string, url: string, sha256: string }} [source]
 */
export function confusablesModule(text, source = SOURCE) {
  const entries = parseConfusables(text).map(([from, to]) => [from, ...to].map((code) => code.toString(16)).join(" "));
  const date = /^# Date: (.+)$/m.exec(text)?.[1]?.trim() ?? "";
  /** @type {string[]} */
  const lines = [];

  for (let start = 0; start < entries.length; start += PER_LINE) lines.push(`  "${entries.slice(start, start + PER_LINE).join(";")}",`);

  return `// Generated by scripts/generate-confusables.js from Unicode's confusables.txt,
// version ${source.version}${date ? ` of ${date}` : ""}:
// ${source.url}
// SHA-256 ${source.sha256}
// Don't edit it: run the script.
//
// © ${/^# © (\d{4})/m.exec(text)?.[1] ?? "2026"} Unicode®, Inc. Unicode and the Unicode Logo are registered
// trademarks of Unicode, Inc. in the U.S. and other countries. Under the
// Unicode License v3: https://www.unicode.org/license.txt

/** The Unicode version of the table. */
export const CONFUSABLES_VERSION = ${JSON.stringify(source.version)};

/**
 * Each character that looks like another, and what it looks like, as hex code
 * points: "source target…", the entries joined by ";", ${entries.length} of them.
 */
export const CONFUSABLES = [
${lines.join("\n")}
].join(";");
`;
}

/**
 * @param {string} text
 * @param {string} sha256
 */
const hashMatches = (text, sha256) => createHash("sha256").update(text, "utf8").digest("hex") === sha256;

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const from = process.argv[2];
  const text = from ? readFileSync(from, "utf8") : await (await fetch(SOURCE.url)).text();

  if (!hashMatches(text, SOURCE.sha256)) {
    console.error(`${from ?? SOURCE.url} isn't Unicode ${SOURCE.version}'s confusables.txt: its SHA-256 differs`);
    process.exitCode = 1;
  } else {
    const out = new URL("../src/confusables.js", import.meta.url);

    writeFileSync(out, confusablesModule(text));
    console.log(`src/confusables.js: ${parseConfusables(text).length} entries of Unicode ${SOURCE.version}`);
  }
}
